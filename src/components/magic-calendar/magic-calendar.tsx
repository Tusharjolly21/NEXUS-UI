// ───────────── helpers ─────────────
const rand = (a: number, b: number) => a + Math.random() * (b - a);
const pick = <T,>(a: T[]) => a[Math.floor(Math.random() * a.length)];
const rgbOf = (hex: string) => {
  const n = parseInt(hex.slice(1, 7), 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
};
const rgba = (hex: string, a: number) => {
  const [r, g, b] = rgbOf(hex);
  return `rgba(${r},${g},${b},${a})`;
};
/** lighter (k > 0) or darker (k < 0) */
const lift = (hex: string, k: number) => {
  const [r, g, b] = rgbOf(hex);
  const f = (v: number) => Math.round(k < 0 ? v * (1 + k) : v + (255 - v) * k);
  return `rgb(${f(r)},${f(g)},${f(b)})`;
};
const sprites = new Map<string, HTMLCanvasElement>();
/** a soft round glow in one colour, drawn once and reused */
const glow = (color: string) => {
  let s = sprites.get(color);
  if (s) return s;
  s = document.createElement("canvas");
  s.width = s.height = 64;
  const g = s.getContext("2d")!;
  const gr = g.createRadialGradient(32, 32, 0, 32, 32, 32);
  gr.addColorStop(0, rgba(color, 1));
  gr.addColorStop(0.2, rgba(color, 0.6));
  gr.addColorStop(0.5, rgba(color, 0.16));
  gr.addColorStop(1, rgba(color, 0));
  g.fillStyle = gr;
  g.fillRect(0, 0, 64, 64);
  sprites.set(color, s);
  return s;
};
const blit = (g: CanvasRenderingContext2D, color: string, x: number, y: number, r: number) =>
  g.drawImage(glow(color), x - r, y - r, r * 2, r * 2);

type Ctx = {
  W: number;
  H: number;
  ox: number;
  oy: number;
  sfx: Sound;
  still?: boolean;
  o?: Opts;
};
/** an effect: it steps, draws over the calendar, and can paint a backdrop behind it */
type Fx = {
  dying: boolean;
  alpha: number;
  step: (dt: number) => boolean;
  draw: (g: CanvasRenderingContext2D, A: number) => void;
  back?: (g: CanvasRenderingContext2D, A: number) => void;
};
const fxOf = (step: Fx["step"], draw: Fx["draw"], back?: Fx["back"]): Fx => ({
  dying: false,
  alpha: 1,
  step,
  draw,
  back,
});

// ───────────── Christmas: snow, settling in a drift ─────────────
function snowFx({ W, H, sfx }: Ctx): Fx {
  type F = {
    x: number;
    y: number;
    z: number;
    r: number;
    vy: number;
    ph: number;
    fr: number;
    rot: number;
    vr: number;
    crystal: boolean;
  };
  const flakes: F[] = [];
  const B = 3,
    n = Math.ceil(W / B) + 2,
    drift = new Float32Array(n);
  let t = 0,
    acc = 0;
  const add = () => {
    const z = 0.25 + Math.pow(Math.random(), 1.5) * 0.75;
    flakes.push({
      x: rand(-30, W + 10),
      y: rand(-30, -4),
      z,
      r: 0.7 + z * 2.3,
      vy: 34 + z * 62,
      ph: rand(0, 6.28),
      fr: rand(0.5, 1.3),
      rot: rand(0, 6.28),
      vr: rand(-0.8, 0.8),
      crystal: z > 0.88 && Math.random() < 0.4,
    });
  };
  [1568, 1319, 1175, 1047, 1319, 1568, 2093].forEach((f, i) =>
    sfx.note(f, { at: i * 0.17, dur: 1.2, gain: 0.026, bell: 0.85 }),
  );
  const crystal = (g: CanvasRenderingContext2D, x: number, y: number, s: number, rot: number, a: number) => {
    g.globalAlpha = a * 0.5;
    blit(g, "#cfe3ff", x, y, s * 1.8);
    g.save();
    g.translate(x, y);
    g.rotate(rot);
    g.globalAlpha = a;
    g.strokeStyle = "#ffffff";
    g.lineWidth = Math.max(0.8, s * 0.15);
    g.lineCap = "round";
    g.beginPath();
    for (let k = 0; k < 6; k++) {
      const an = (k * Math.PI) / 3,
        cx = Math.cos(an),
        sy = Math.sin(an);
      g.moveTo(0, 0);
      g.lineTo(cx * s, sy * s);
      const bx = cx * s * 0.55,
        by = sy * s * 0.55,
        l = s * 0.34;
      for (const sg of [-1, 1]) {
        const a2 = an + sg * 0.85;
        g.moveTo(bx, by);
        g.lineTo(bx + Math.cos(a2) * l, by + Math.sin(a2) * l);
      }
    }
    g.stroke();
    g.restore();
  };
  return fxOf(
    (dt) => {
      t += dt;
      acc += (t < 6 ? 80 : 26) * dt;
      while (acc > 1 && flakes.length < 340) {
        acc--;
        add();
      }
      const wind = 9 + Math.sin(t * 0.35) * 9;
      for (let i = flakes.length - 1; i >= 0; i--) {
        const f = flakes[i];
        f.y += f.vy * dt;
        f.x += (wind * f.z + Math.sin(t * f.fr + f.ph) * 16 * f.z) * dt;
        f.rot += f.vr * dt;
        const bi = Math.max(0, Math.min(n - 1, Math.round(f.x / B)));
        if (f.y >= H - drift[bi] - f.r * 0.4) {
          if (f.x > 0 && f.x < W)
            for (let k = -3; k <= 3; k++) {
              const j = bi + k;
              if (j >= 0 && j < n) drift[j] = Math.min(20, drift[j] + f.r * 0.32 * (1 - Math.abs(k) * 0.22));
            }
          flakes.splice(i, 1);
        } else if (f.x > W + 30) f.x = -20;
      }
      // a drift settles soft, not in spikes
      for (let i = 1; i < n - 1; i++) drift[i] += (drift[i - 1] + drift[i + 1] - 2 * drift[i]) * Math.min(0.45, dt * 6);
      return true;
    },
    (g, A) => {
      g.beginPath();
      g.moveTo(-2, H + 2);
      for (let i = 0; i < n; i++) g.lineTo(i * B, H - drift[i]);
      g.lineTo(W + 2, H + 2);
      g.closePath();
      const gr = g.createLinearGradient(0, H - 22, 0, H);
      gr.addColorStop(0, "#ffffff");
      gr.addColorStop(1, "#c6d8f5");
      g.fillStyle = gr;
      g.globalAlpha = A * 0.96;
      g.fill();
      for (const f of flakes) {
        const a = A * (0.4 + 0.6 * f.z);
        if (f.crystal) crystal(g, f.x, f.y, 2.6 + f.z * 4.4, f.rot, a);
        else {
          g.globalAlpha = a;
          blit(g, "#ffffff", f.x, f.y, f.r * 2.6);
        }
      }
    },
  );
}

// ───────────── New Year's Eve: fireworks ─────────────
function fireworksFx({ W, H, ox, sfx, still, o }: Ctx): Fx {
  const G = 230;
  type R = {
    x: number;
    y: number;
    vx: number;
    vy: number;
    hx: number;
    hy: number;
    pal: string[];
    type: number;
  };
  type P = {
    x: number;
    y: number;
    hx: number;
    hy: number;
    vx: number;
    vy: number;
    life: number;
    max: number;
    col: string;
    w: number;
    drag: number;
    k: number;
    crackle: boolean;
    tw: number;
  };
  const rockets: R[] = [],
    parts: P[] = [],
    flashes: { x: number; y: number; col: string; a: number }[] = [];
  const PAL = o?.pal
    ? o.pal.map((c, i, a) => [c, a[(i + 1) % a.length]])
    : [
        ["#ff4d6d", "#ffd166"],
        ["#64d2ff", "#ffffff"],
        ["#c77dff", "#ff8fd8"],
        ["#5cff9d", "#e6ff8a"],
        ["#ffd60a", "#ff9f0a"],
        ["#ffffff", "#9ad8ff"],
      ];
  let t = 0,
    next = 0.1,
    n = 0;
  const launch = () => {
    const x = n === 0 ? ox : rand(W * 0.14, W * 0.86);
    const ty = rand(H * 0.1, H * 0.4),
      y0 = H + 6;
    rockets.push({
      x,
      y: y0,
      vx: rand(-18, 18),
      vy: -Math.sqrt(2 * G * (y0 - ty)),
      hx: x,
      hy: y0,
      pal: pick(PAL),
      type: n === 0 ? 0 : Math.floor(Math.random() * 4),
    });
    n++;
    sfx.whoosh(260, 1100, { dur: 0.8, gain: 0.018 });
  };
  const burst = (r: R) => {
    const { x, y, type } = r;
    const count = type === 2 ? 90 : type === 1 ? 54 : 110;
    const sp = type === 2 ? 140 : rand(150, 215);
    for (let i = 0; i < count; i++) {
      let vx: number, vy: number;
      if (type === 1) {
        const a = (i / count) * Math.PI * 2 + rand(-0.04, 0.04),
          k = rand(0.92, 1.04);
        vx = Math.cos(a) * sp * k;
        vy = Math.sin(a) * sp * 0.5 * k;
      } else {
        // a sphere seen from the side: dense in the middle, like the real thing
        const u = rand(-1, 1),
          th = rand(0, Math.PI * 2),
          s = Math.sqrt(1 - u * u),
          k = rand(0.9, 1);
        vx = s * Math.cos(th) * sp * k;
        vy = s * Math.sin(th) * sp * k;
      }
      const willow = type === 2;
      parts.push({
        x,
        y,
        hx: x,
        hy: y,
        vx,
        vy,
        life: 0,
        max: willow ? rand(2.2, 3) : rand(1.3, 1.9),
        col: willow ? pick(["#ffd27a", "#ffb347", "#ffe7a8"]) : Math.random() < 0.72 ? r.pal[0] : r.pal[1],
        w: willow ? 1.3 : 1.8,
        drag: willow ? 2.3 : 1.25,
        k: willow ? 3.2 : 11,
        crackle: type === 3 && Math.random() < 0.55,
        tw: rand(0, 6),
      });
    }
    flashes.push({ x, y, col: r.pal[0], a: 1 });
    sfx.note(62, { dur: 1.1, gain: 0.16, bell: 0, glide: 34 });
    sfx.whoosh(3600, 600, { dur: 0.6, gain: 0.03 });
    if (type === 3)
      for (let i = 0; i < 12; i++)
        sfx.tick({
          at: 0.85 + Math.random() * 0.7,
          freq: rand(2600, 5200),
          gain: 0.012,
        });
  };
  return fxOf(
    (dt) => {
      t += dt;
      next -= dt;
      if (next <= 0) {
        launch();
        next = t < 6 ? rand(0.45, 0.85) : rand(1.6, 3);
      }
      for (let i = rockets.length - 1; i >= 0; i--) {
        const r = rockets[i];
        r.vy += G * dt;
        r.x += r.vx * dt;
        r.y += r.vy * dt;
        r.hx += (r.x - r.hx) * Math.min(1, dt * 9);
        r.hy += (r.y - r.hy) * Math.min(1, dt * 9);
        if (r.vy > -28) {
          burst(r);
          rockets.splice(i, 1);
        }
      }
      for (let i = parts.length - 1; i >= 0; i--) {
        const p = parts[i];
        p.life += dt;
        const d = Math.exp(-p.drag * dt);
        p.vx *= d;
        p.vy = p.vy * d + 72 * dt;
        p.x += p.vx * dt;
        p.y += p.vy * dt;
        p.hx += (p.x - p.hx) * Math.min(1, dt * p.k);
        p.hy += (p.y - p.hy) * Math.min(1, dt * p.k);
        if (p.crackle && p.life > p.max * 0.55) {
          p.crackle = false;
          for (let k = 0; k < 3; k++)
            parts.push({
              x: p.x,
              y: p.y,
              hx: p.x,
              hy: p.y,
              vx: rand(-60, 60),
              vy: rand(-60, 60),
              life: 0,
              max: rand(0.25, 0.45),
              col: "#fff6dc",
              w: 1,
              drag: 3,
              k: 20,
              crackle: false,
              tw: rand(0, 6),
            });
        }
        if (p.life > p.max) parts.splice(i, 1);
      }
      for (let i = flashes.length - 1; i >= 0; i--) if ((flashes[i].a -= dt * 2.4) <= 0) flashes.splice(i, 1);
      return true;
    },
    (g, A) => {
      g.globalCompositeOperation = "lighter";
      // held still (reduced motion), a flash or a rocket in mid-climb just reads as a smudge
      if (!still)
        for (const f of flashes) {
          g.globalAlpha = A * f.a * 0.4;
          blit(g, f.col, f.x, f.y, 190);
        }
      g.lineCap = "round";
      if (!still)
        for (const r of rockets) {
          g.globalAlpha = A * 0.9;
          g.strokeStyle = "#ffd9a0";
          g.lineWidth = 1.6;
          g.beginPath();
          g.moveTo(r.hx, r.hy + 10);
          g.lineTo(r.x, r.y);
          g.stroke();
          blit(g, "#ffe2b0", r.x, r.y, 6);
        }
      for (const p of parts) {
        const k = 1 - p.life / p.max;
        let a = k * k * 1.4;
        if (p.max < 0.5) a *= 0.55 + 0.45 * Math.sin(p.life * 60 + p.tw);
        g.globalAlpha = Math.min(1, A * a);
        g.strokeStyle = p.col;
        g.lineWidth = p.w * (0.55 + 0.45 * k);
        g.beginPath();
        g.moveTo(p.hx, p.hy);
        g.lineTo(p.x, p.y);
        g.stroke();
        blit(g, p.col, p.x, p.y, 3.2 * (0.5 + k * 0.5));
      }
    },
  );
}

