/** Easter Sunday, by the Gregorian computus */
const easter = (y: number) => {
  const a = y % 19,
    b = Math.floor(y / 100),
    c = y % 100,
    d = Math.floor(b / 4),
    e = b % 4,
    f = Math.floor((b + 8) / 25),
    g = Math.floor((b - f + 1) / 3),
    h = (19 * a + b - d - g + 15) % 30,
    i = Math.floor(c / 4),
    k = c % 4,
    l = (32 + 2 * e + 2 * i - h - k) % 7,
    m = Math.floor((a + 11 * h + 22 * l) / 451),
    n = h + l - 7 * m + 114;
  return new Date(y, Math.floor(n / 31) - 1, (n % 31) + 1);
};
const fromEaster = (days: number) => (y: number) => {
  const e = easter(y);
  const t = new Date(e.getFullYear(), e.getMonth(), e.getDate() + days);
  return [[t.getMonth(), t.getDate()]] as [number, number][];
};

