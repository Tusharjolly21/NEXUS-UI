/** Every land cell as an [x, y] pair, ready to draw as a dot. Computed once on first use. */
let landDots: [number, number][] | null = null;
export function getLandDots(): readonly [number, number][] {
  if (landDots) return landDots;
  const dots: [number, number][] = [];
  LAND_ROWS.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) if (row[x] === "#") dots.push([x, y]);
  });
  landDots = dots;
  return dots;
}
